#!/usr/bin/env node
/**
 * Generates `docs/release-notes.md` from the repository `CHANGELOG.md`.
 *
 * Runs automatically before `npm run build` and `npm start` (see the `prebuild`
 * and `prestart` scripts in package.json), so the published page never drifts
 * from the changelog. The generated page is committed as well: the Azure Static
 * Web Apps build runs in an Oryx container where only the `docs/` app folder is
 * guaranteed to be present, so if `CHANGELOG.md` cannot be read we keep the
 * committed page instead of failing the deploy.
 *
 * The CI `Build` job re-runs this and fails on a diff, which is what keeps the
 * committed copy honest.
 */

import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const changelogPath = path.join(scriptDir, '..', '..', 'CHANGELOG.md');
const outputPath = path.join(scriptDir, '..', 'docs', 'release-notes.md');

const REPO = 'https://github.com/datacontract/datacontract-cli';

const FRONT_MATTER = `---
sidebar_position: 22
title: "Release Notes"
description: "What changed in every release of the Data Contract CLI — new importers, exporters, data sources, and fixes, newest first."
slug: /release-notes
mdx:
  # Parsed as CommonMark rather than MDX: changelog entries contain literal
  # angle brackets and braces (e.g. \`--schema <PATH>\`, \`{object}\` placeholders)
  # that MDX would try to read as JSX and expressions.
  format: md
# The page has one heading per release; without this the right-hand table of
# contents would also list every "Added"/"Fixed" subsection.
toc_max_heading_level: 2
---
`;

const INTRO = `# Release Notes

Every released version of the Data Contract CLI, newest first. The CLI follows
[Semantic Versioning](https://semver.org/spec/v2.0.0.html); breaking changes are
marked as such in the entry.

- Install or upgrade with \`uv tool install --upgrade datacontract-cli\` or \`pip install --upgrade datacontract-cli\` — see [Installation](./installation.md).
- Packages: [PyPI](https://pypi.org/project/datacontract-cli/#history) · [Docker Hub](https://hub.docker.com/r/datacontract/cli/tags) · [GitHub releases](${REPO}/releases)
`;

/** Split a line into code spans and prose, so we only rewrite the prose. */
function mapOutsideCode(line, fn) {
  return line
    .split(/(`[^`]*`)/g)
    .map((segment) => (segment.startsWith('`') ? segment : fn(segment)))
    .join('');
}

/**
 * Turn the `(#1220 @DMZ22)` credits the changelog convention appends to an
 * entry into links to the issue and the contributor.
 */
function linkifyCredits(line) {
  return mapOutsideCode(line, (text) =>
    text
      .replace(/(?<![\w[])#(\d+)\b/g, `[#$1](${REPO}/issues/$1)`)
      .replace(/(?<![\w[/])@([A-Za-z\d](?:[A-Za-z\d]|-(?=[A-Za-z\d])){0,38})\b/g, '[@$1](https://github.com/$1)'),
  );
}

/**
 * Links in the changelog are relative to the repository root (`./README.md#…`).
 * Point them at GitHub so they resolve on the docs site.
 */
function absolutizeRepoLinks(line) {
  return mapOutsideCode(line, (text) =>
    text.replace(/\]\((?!https?:\/\/|#|mailto:)\.?\/?([^)\s]+)\)/g, `](${REPO}/blob/main/$1)`),
  );
}

/** `## [1.0.14] - 2026-07-23` -> `## 1.0.14 — 2026-07-23 {#v1-0-14}` */
function rewriteReleaseHeading(line) {
  const match = line.match(/^## \[(.+?)\](?:\s*-\s*(\S+))?\s*$/);
  if (!match) {
    return line;
  }
  const [, version, date] = match;
  if (version.toLowerCase() === 'unreleased') {
    return '## Unreleased {#unreleased}';
  }
  const anchor = `v${version.replace(/\./g, '-')}`;
  return `## ${version}${date ? ` — ${date}` : ''} {#${anchor}}`;
}

function generate(changelog) {
  const body = changelog
    // Drop the changelog's own title and the Keep a Changelog preamble; the
    // page has its own introduction. Everything from the first release heading.
    .slice(changelog.search(/^## /m))
    .split('\n')
    .map((line) =>
      line.startsWith('## ') ? rewriteReleaseHeading(line) : absolutizeRepoLinks(linkifyCredits(line)),
    )
    .join('\n')
    .trimEnd();

  return `${FRONT_MATTER}\n<!-- AUTOGENERATED from CHANGELOG.md by docs/scripts/generate-release-notes.mjs. Do not edit by hand. -->\n\n${INTRO}\n${body}\n`;
}

if (!existsSync(changelogPath)) {
  if (existsSync(outputPath)) {
    console.warn(`[release-notes] ${changelogPath} not found — keeping the committed ${path.basename(outputPath)}.`);
    process.exit(0);
  }
  console.error(`[release-notes] ${changelogPath} not found and no committed page to fall back to.`);
  process.exit(1);
}

const generated = generate(readFileSync(changelogPath, 'utf8'));
const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null;

if (generated === current) {
  console.log('[release-notes] docs/release-notes.md is up to date.');
} else {
  writeFileSync(outputPath, generated);
  console.log(`[release-notes] Wrote ${path.relative(path.join(scriptDir, '..'), outputPath)} from CHANGELOG.md.`);
}
